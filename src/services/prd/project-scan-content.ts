/**
 * The two project-scan.md CONTENT BUILDERS: the 0-1 placeholder and the
 * existing-project scan.
 *
 * Split out of `project-scan-bootstrap-service.ts`. That file owns the
 * create-or-skip decision and the envelope; this one owns what the file says,
 * and nothing here makes a decision. The split is a size split — the bootstrap
 * file carries a lint ceiling that may only shrink, and the refresh feature had
 * to fit under it.
 *
 * Both builders are reached from the CREATE path only. An existing file is never
 * regenerated: its machine fields are refreshed in place
 * (`project-scan-field-refresh.ts`) and its prose is sediment.
 */

import type { ArchetypeReport } from '../scan/scan-types.js';
import type { LibraryReport } from '../scan/libraries-types.js';
import { renderFrontmatterField } from './project-scan-field-refresh.js';

/** Build the project-scan.md content for a 0-1 project (empty placeholders). */
export function buildZeroToOneProjectScan(): string {
  const now = new Date().toISOString();
  return [
    ...zeroToOneFrontmatter(now),
    '',
    '# Project Scan (0-1 bootstrap)',
    '',
    `> Auto-generated by \`peaks workspace init\` / \`peaks project context\` on ${now}. ` +
      'Refresh with `peaks project context --project <repo>` once the project has a `package.json` + source files.',
    '',
    ...ZERO_TO_ONE_SECTIONS,
    ''
  ].join('\n');
}

function zeroToOneFrontmatter(now: string): string[] {
  return [
    '---',
    'schemaVersion: 1',
    `capturedAt: ${now}`,
    'archetype: unknown',
    'confidence: low',
    'techStack: {}',
    'libraryVersions: {}',
    'architecture: ""',
    'karpathySelfCheck: {}',
    '---'
  ];
}

