/** Render a LibraryReport as a markdown table body (header row included). */
function renderLibraryTable(libraryReport: LibraryReport): string {
  const header = '| Package | Pinned range | Major | Scope | Ecosystem |';
  const sep = '|---|---|---|---|---|';
  if (libraryReport.libraries.length === 0) {
    return [header, sep, '| (empty) | — | — | — | — |'].join('\n');
  }
  const rows = libraryReport.libraries.map((entry) => {
    const major = entry.major === null ? '—' : String(entry.major);
    return `| \`${entry.name}\` | \`${entry.version}\` | ${major} | ${entry.scope} | ${entry.ecosystem} |`;
  });
  return [header, sep, ...rows].join('\n');
}

/** Build the project-scan.md content for an existing project. */
export function buildExistingProjectScan(args: {
  archetypeReport: ArchetypeReport;
  libraryReport: LibraryReport;
  techStack: Readonly<Record<string, string>>;
}): string {
  const { archetypeReport, libraryReport, techStack } = args;
  const now = new Date().toISOString();

  // Library versions snapshot: a flat {name: version} map. Mirrors the shape
  // consumed by `services/prd/project-scan-types.ts`
  // `ProjectScanLibraryVersions`.
  const libraryVersionsMap: Record<string, string> = {};
  for (const entry of libraryReport.libraries) {
    libraryVersionsMap[entry.name] = entry.version;
  }

  return [
    ...existingFrontmatter({ now, archetypeReport, techStack, libraryVersionsMap }),
    '',
    `# Project Scan (refreshed ${now})`,
    '',
    '> Auto-generated by `peaks workspace init` / `peaks project context`.',
    '',
    ...archetypeSections(archetypeReport),
    ...techStackSection(techStack),
    '## Library versions',
    '',
    renderLibraryTable(libraryReport),
    '',
    '## Architecture',
    '',
    `_Auto-generated from \`scanArchetype\` signals — see archetypeReport.backendFrameworks / .backendDirsPresent / .swaggerPaths in \`.peaks/_runtime/<sid>/rd/project-scan.md\` (legacy) or \`.peaks/project-scan/project-scan.md\` (this file) for the raw facts._`,
    '',
    '## Karpathy self-check',
    '',
    '| Guideline | Where enforced |',
    '|---|---|',
    '| §1 Think Before Coding | (refresh with LLM review) |',
    '| §2 Simplicity First | (refresh with LLM review) |',
    '| §3 Surgical Changes | (refresh with LLM review) |',
    '| §4 Goal-Driven Execution | (refresh with LLM review) |',
    '',
    '## Refresh procedure',
    '',
    '1. Re-run `peaks scan archetype --project <repo> --json` and `peaks scan libraries --project <repo> --json` after any dependency / archetype change.',
    '2. Re-run `peaks project context --project <repo>` to refresh this file. Its frontmatter is refreshed in place; the prose below it is yours.',
    '3. Commit the regenerated project-scan.md alongside the dependency bump.',
    ''
  ].join('\n');
}

function existingFrontmatter(args: {
  now: string;
  archetypeReport: ArchetypeReport;
  techStack: Readonly<Record<string, string>>;
  libraryVersionsMap: Readonly<Record<string, string>>;
}): string[] {
  return [
    '---',
    'schemaVersion: 1',
    `capturedAt: ${args.now}`,
    `archetype: ${args.archetypeReport.archetype}`,
    `confidence: ${args.archetypeReport.confidence}`,
    renderFrontmatterField('techStack', args.techStack),
    renderFrontmatterField('libraryVersions', args.libraryVersionsMap),
    'architecture: ""',
    'karpathySelfCheck: {}',
    '---'
  ];
}

/** The `## Archetype` and `## Project mode` tables, from the archetype report. */
function archetypeSections(report: ArchetypeReport): string[] {
  return [
    '## Archetype',
    '',
    '| Field | Value |',
    '|---|---|',
    `| Type | \`${report.archetype}\` |`,
    `| Confidence | \`${report.confidence}\` |`,
    '',
    '## Project mode',
    '',
    '| Field | Value |',
    '|---|---|',
    `| Integration mode | ${report.integrationMode} |`,
    `| Integration mode reason | ${report.integrationModeReason} |`,
    `| Frontend-only | \`${String(report.frontendOnly)}\` |`,
    `| Reason | ${report.frontendOnlyReason} |`,
    ''
  ];
}

/**
 * The `## Tech stack` table. Every value here is machine-derived, so the table
 * is a projection of the `techStack` frontmatter — a refresh rewrites that
 * frontmatter and leaves this table to the create path.
 */
function techStackSection(techStack: Readonly<Record<string, string>>): string[] {
  return [
    '## Tech stack',
    '',
    '| Concern | Value |',
    '|---|---|',
    `| Language | ${techStack['language'] ?? '(unknown)'} |`,
    `| Package manager | ${techStack['packageManager'] ?? '(unknown)'} |`,
    `| Node runtime | ${techStack['runtime'] ?? '(unknown)'} |`,
    `| Build | ${techStack['buildTool'] ?? '(no package.json build script)'} |`,
    ''
  ];
}
